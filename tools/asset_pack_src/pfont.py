def text_mask(s,gap=1):
    cols=[]; 
    for ch in s.upper():
        g=[r for r in G[ch].split()]; cols.append(g)
    w=sum(5+gap for _ in cols)-gap; m=set()
    x=0
    for g in cols:
        for y,row in enumerate(g):
            for i,c in enumerate(row):
                if c=='1': m.add((x+i,y))
        x+=5+gap
    return m,w,7
